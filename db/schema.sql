CREATE TABLE IF NOT EXISTS learners (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  age SMALLINT CHECK (age IS NULL OR (age BETWEEN 1 AND 120)),
  phone VARCHAR(20) NOT NULL DEFAULT '',
  location VARCHAR(120) NOT NULL DEFAULT '',
  learning_goal VARCHAR(120) NOT NULL DEFAULT '',
  experience VARCHAR(30) NOT NULL DEFAULT 'Beginner',
  privacy_consent BOOLEAN NOT NULL DEFAULT FALSE,
  privacy_consent_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE learners
  ADD COLUMN IF NOT EXISTS privacy_consent BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE learners
  ADD COLUMN IF NOT EXISTS privacy_consent_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS videos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(80) NOT NULL DEFAULT 'General',
  description VARCHAR(500) NOT NULL DEFAULT '',
  video_url TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lessons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(80) NOT NULL,
  description VARCHAR(500) NOT NULL,
  steps TEXT NOT NULL,
  icon VARCHAR(20) NOT NULL
);

CREATE INDEX IF NOT EXISTS learners_created_at_idx ON learners (created_at DESC);
CREATE INDEX IF NOT EXISTS videos_created_at_idx ON videos (created_at DESC);
